def test_traffic(client, sim_conn):
    create_poll(client, id="t", quantity=1)
    ok_data(client, "t")
    entries = client.get("/api/traffic", params={"connection_id": "sim"}).json()
    assert {e["direction"] for e in entries} == {"tx", "rx"}
    tx = next(e for e in entries if e["direction"] == "tx")
    # MBAP header (length 6, unit 1) followed by FC03, address 0, quantity 1
    assert tx["hex"].endswith("00 00 00 06 01 03 00 00 00 01")
    last = entries[-1]["seq"]
    assert all(e["seq"] > last for e in client.get(f"/api/traffic?after_seq={last}").json())
    assert client.delete("/api/traffic").status_code == 204


